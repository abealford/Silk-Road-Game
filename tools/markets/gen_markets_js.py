#!/usr/bin/env python3
"""Generate src/markets_data.js from the design data (goods_data.py, markets.py).

    python3 tools/markets/gen_markets_js.py

The 253 goods and 11 markets are designed in claude/silk-road-goods-catalogue.md
and claude/silk-road-markets.md; edit the .py files here, then re-run this."""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); sys.path.insert(0, HERE)
from goods_data import GOODS, DEMAND
import markets
ROOT = os.path.dirname(os.path.dirname(HERE))
# goods that carry over from v18 keep their old ids (the story, events, wars, guilds and saves use them)
OLD = {'Hangzhou silk':'silk','Qingbai porcelain':'porcelain','Sichuan brick tea':'tea','Lacquerware':'lacquer','Ginger':'ginger','Rhubarb root':'rhubarb',
 'Tibetan musk':'musk','Khotan green jade':'jade','Samarkand paper':'paper','Turkoman carpets':'carpets','Tabriz gold brocade':'brocade','Mosul muslin':'muslin',
 'Enamelled glass':'glass','Damascus steel':'blades','Rosewater':'rosewater','Olive oil':'olive','Flemish woollens':'wool','Red coral':'coral','Baltic amber':'amber',
 'Sable furs':'furs','Wax':'wax','Lapis lazuli':'lapis','Balas ruby':'rubies','Nishapur turquoise':'turquoise','Saffron':'saffron','Malabar pepper':'pepper',
 'Frankincense':'incense','Hormuz indigo':'indigo','Dates':'dates','Dried fruit & nuts':'fruit','Greek wine':'wine','Kipchak felt':'felt','Caspian raw silk':'rawsilk',
 'Naphtha':'naphtha','Raw cotton':'cotton','Sal ammoniac':'salammoniac','Jasper & chalcedony':'chalcedony','Saddles & bridles':'horsegear','Erzincan buckram':'buckram',
 'Gujarati printed cloth':'cottoncloth','Pearls of Mannar':'pearls','Ceylon cinnamon':'cinnamon','Cloves & nutmeg':'spices','Sandalwood':'sandalwood','Ivory':'ivory',
 'Champa aloeswood':'aloeswood','Malay tin':'tin','Cane sugar':'sugar','Egyptian linen':'linen','Balsam of Matariya':'balsam','Egyptian emeralds':'emeralds',
 'Areca & betel':'betel','Yemeni carnelian':'carnelian','Gold dust':'golddust','Yunnan salt cakes':'salt','Changthang wool':'pashmina','Cowrie shells':'cowries',
 'Oil from the Holy Sepulchre':'holyoil'}
assert len(set(OLD.values())) == len(OLD)
UNIT = [(r'wine|oil\b|sauce|honey|naphtha|caviar|attar|ghee|fire|aloe$', 'jar'), (r'muslin|silk|brocade|samite|satin|taffeta|linen|calico|cloth|burd|chintz|woollens|buckram|mohair|tapestry|shawl|ramie|sacking|velvet', 'bolt'),
 (r'horse|pony|mare|elephant|tiger|gyrfalcon', 'head'), (r'pelt|furs|vair|skin|hides|ermine|goatskins|coats', 'bundle'), (r'carpet', 'roll'), (r'timber|teak|ebony|sappanwood|rattan', 'log'),
 (r'manuscript|book|gospel|scroll|kangyur|thangka|painting', 'volume'), (r'statue|bronze|icon|relic|globe|astrolabe|ewer|plate|carving|howdah|tent|buddha|belt|lamp|bowl|sword|steel|bows', 'piece'),
 (r'porcelain|celadon|ware\b|tiles|jars|ware$|pots|copperware|brassware|glass|lacquer', 'crate'), (r'umbrellas|fans', 'bundle'), (r'tea', 'brick'), (r'salt', 'cake'), (r'ingots|bars|silver|tin|iron|copper', 'ingot')]
def unit(name, size, typ):
    n = name.lower()
    for pat, u in UNIT:
        if re.search(pat, n): return u
    return {'C': 'pouch', 'M': 'bundle', 'B': 'sack'}[size]
def slug(name):
    return re.sub(r'[^a-z0-9]+', '', name.lower().replace('&', 'and'))[:22]
SIZE = {'B': 'bulky', 'M': 'medium', 'C': 'compact'}
goods = []; ids = set()
for m in markets.MARKETS:
    for r in ['c', 'u', 'r', 'e', 'l']:
        for name, size, price, src, typ, note in GOODS[m['id']][r]:
            gid = OLD.get(name) or slug(name)
            assert gid not in ids, gid; ids.add(gid)
            goods.append(dict(id=gid, name=name, m=m['id'], rar=r, size=SIZE[size], base=price, prod=src, type=typ, unit=unit(name, size, typ), blurb=note))
mk = [dict(id=m['id'], name=m['name'], color=m['color'], hub=m['hub'], stars=m['stars'], special=m['special'], cities=m['cities'].split(), based=m['based'], why=m['why'], lab=m['lab']) for m in markets.MARKETS]
out = ('// GENERATED by tools/markets/gen_markets_js.py from the design data. Do not edit by hand.\n'
       f'const MARKETS_DATA = {json.dumps(mk, ensure_ascii=False)};\n'
       f'const MARKET_GOODS = [\n' + ',\n'.join(json.dumps(g, ensure_ascii=False) for g in goods) + '\n];\n'
       f'const MARKET_DEMAND = {json.dumps(DEMAND)};\n')
open(os.path.join(ROOT, 'src', 'markets_data.js'), 'w', encoding='utf-8').write(out)
print(len(goods), 'goods,', len(mk), 'markets ->', 'src/markets_data.js', len(out), 'bytes')
missing = set(OLD.values()) - ids; print('old ids kept:', len(set(OLD.values()) & ids), 'missing:', missing)
